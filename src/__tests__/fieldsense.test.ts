import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { NAV_GROUPS } from '../components/Layout';

describe('FieldSense AI Frontend & Repository Integrity', () => {
  it('registers all 17 required navigation pages', () => {
    const pages = NAV_GROUPS.flatMap((g) => g.items.map((i) => i.id));
    expect(pages).toHaveLength(17);
    expect(new Set(pages).size).toBe(17);
  });

  it('has verified dataset registry and model registry JSON files', () => {
    const root = process.cwd();
    const datasets = JSON.parse(
      fs.readFileSync(path.join(root, 'data/dataset_registry.json'), 'utf-8'),
    );
    const models = JSON.parse(
      fs.readFileSync(path.join(root, 'data/model_registry.json'), 'utf-8'),
    );
    expect(Array.isArray(datasets)).toBe(true);
    expect(datasets.length).toBeGreaterThanOrEqual(5);
    expect(Array.isArray(models)).toBe(true);
    expect(models.some((m: { evaluation_status: string }) => m.evaluation_status === 'VERIFIED')).toBe(
      true,
    );
  });

  it('has real CPU benchmark artifact generated by run_local_benchmarks.py', () => {
    const root = process.cwd();
    const bench = JSON.parse(
      fs.readFileSync(path.join(root, 'experiments/results/cpu_benchmarks.json'), 'utf-8'),
    );
    expect(Array.isArray(bench.benchmarks)).toBe(true);
    expect(bench.benchmarks.length).toBeGreaterThanOrEqual(4);
  });
});
